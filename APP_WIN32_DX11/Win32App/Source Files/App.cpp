int App::Go()
{
	while (true)
	{
		// Process all messages pending, but to not block for new messages
		if (const auto ecode = Window::ProcessMessages())
		{
			// If return optional has value, means we're quitting so return exit code
			return *ecode;
		}
		else
			DoFrame();
	}
}
